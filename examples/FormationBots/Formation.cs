    static Formation()
    {
        // кириллица, совпадающая с латиницей — те же глифы
        foreach (var (cyr, lat) in new[]
                 {
                     ('А', 'A'), ('В', 'B'), ('Е', 'E'), ('К', 'K'), ('М', 'M'), ('Н', 'H'),
                     ('О', 'O'), ('Р', 'P'), ('С', 'C'), ('Т', 'T'), ('Х', 'X'),
                 })
            Font[cyr] = Font[lat];
    }

    // строчные без своего глифа (вся кириллица) рисуются заглавным
    private static bool TryGlyph(char ch, out string[] glyph)
        => Font.TryGetValue(ch, out glyph!) || Font.TryGetValue(char.ToUpperInvariant(ch), out glyph!);

    /// <summary>Точки надписи в клетках, (0,0) — левый верхний угол; Letter — номер буквы для поочерёдной сборки.</summary>
    public static List<(int Col, int Row, int Letter)> Layout(string text)
    {
        var points = new List<(int, int, int)>();
        var col = 0;
        for (var letter = 0; letter < text.Length; letter++)
        {
            if (!TryGlyph(text[letter], out var glyph))
                throw new ArgumentException($"Нет глифа для символа '{text[letter]}'");

            for (var row = 0; row < glyph.Length; row++)
            for (var i = 0; i < glyph[row].Length; i++)
                if (glyph[row][i] == '#')
                    points.Add((col + i, row, letter));

            col += glyph[0].Length + 1; // межбуквенный зазор в одну клетку
        }

        return points;
    }

    /// <summary>Ширина надписи в клетках — для центрирования у спавна.</summary>
    public static int Width(string text)
        => text.Sum(ch => TryGlyph(ch, out var glyph) ? glyph[0].Length + 1 : 0) - 1;

    /// <summary>Символы текста, которых нет в шрифте.</summary>
    public static List<char> Unknown(string text)
        => text.Where(ch => !TryGlyph(ch, out _)).Distinct().ToList();
